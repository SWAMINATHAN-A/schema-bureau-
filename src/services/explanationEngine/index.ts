import type {
  Column,
  ParsedSchema,
  Relationship,
  SimulationStep,
  TableSchema } from
'../../types/schema';
import { describeType } from '../sqlParser/dataTypes';

export function explainTable(table: TableSchema): string {
  const pk = table.primaryKeys.length ?
  `Its identity is carried by ${table.primaryKeys.length > 1 ? 'the composite key' : 'the primary key'} ${table.primaryKeys.join(
    ' + '
  )}.` :
  'It declares no primary key, so its rows have no guaranteed identity.';
  const fk = table.foreignKeys.length ?
  ` It participates in ${table.foreignKeys.length} relationship(s) through ${table.foreignKeys.
  map((f) => f.columns.join('+')).
  join(', ')}.` :
  ' It holds no foreign keys, so it does not depend on another entity.';
  return `${table.name} becomes an entity because each CREATE TABLE statement declares a distinct set of real-world things worth storing. It has ${table.columns.length} attribute(s). ${pk}${fk}`;
}

export function explainColumn(table: TableSchema, column: Column): string {
  const info = describeType(column.baseType);
  const parts = [
  `${table.name}.${column.name} is declared as ${column.dataType}. ${info.description}`];

  if (column.primaryKey) {
    parts.push(
      table.primaryKeys.length > 1 ?
      `It is part of the composite primary key (${table.primaryKeys.join(', ')}), so only the combination of those columns is unique.` :
      'It is the primary key, so every row must supply a distinct, non-null value.'
    );
  }
  if (column.foreignKey) {
    const fk = table.foreignKeys.find((f) => f.columns.some((c) => c.toLowerCase() === column.name.toLowerCase()));
    if (fk) parts.push(`It is a foreign key pointing at ${fk.refTable}${fk.refColumns.length ? `(${fk.refColumns.join(', ')})` : ''}, which is what draws the relationship line in the diagram.`);
  }
  if (column.unique && !column.primaryKey) {
    parts.push('A UNIQUE constraint means no two rows may repeat this value, though it may be absent when nullable.');
  }
  if (!column.nullable && !column.primaryKey) {
    parts.push('NOT NULL makes this a mandatory attribute — a row cannot exist without it.');
  }
  if (column.defaultValue) {
    parts.push(`When no value is supplied the engine stores ${column.defaultValue}.`);
  }
  if (column.autoIncrement) {
    parts.push('Values are generated by the database rather than the application — a surrogate key.');
  }
  return parts.join(' ');
}

export function explainPrimaryKey(table: TableSchema): string {
  if (table.primaryKeys.length === 0) {
    return `${table.name} has no PRIMARY KEY constraint. In ER terms it has no identifier, which means two identical rows could not be told apart and no other entity can reliably reference it.`;
  }
  if (table.primaryKeys.length === 1) {
    return `${table.primaryKeys[0]} is identified as the primary key of ${table.name} because it is declared with the PRIMARY KEY constraint. In the ER model it is the identifying attribute of the entity, drawn underlined by convention.`;
  }
  return `${table.name} uses a composite primary key made of ${table.primaryKeys.join(
    ' + '
  )}. No single one of those columns identifies a row; only their combination does. Composite keys most often appear on associative entities that record a pairing.`;
}

export function explainForeignKey(table: TableSchema, relationship: Relationship): string {
  return `${relationship.sourceColumn} connects ${relationship.sourceTable} to ${relationship.targetTable} because it references ${relationship.targetTable}.${relationship.targetColumn}. The database will refuse any ${relationship.sourceTable} row whose ${relationship.sourceColumn} has no matching ${relationship.targetTable} row — that guarantee is called referential integrity.`;
}

export function explainRelationship(relationship: Relationship): string {
  const label = cardinalityLabel(relationship);
  return `${label}. ${relationship.reason} This cardinality is inferred from the constraints in your SQL; business rules that live outside the schema could narrow it further.`;
}

export function cardinalityLabel(relationship: Relationship): string {
  switch (relationship.type) {
    case 'one-to-one':
      return `One ${relationship.sourceTable} → one ${relationship.targetTable}`;
    case 'many-to-one':
      return `Many ${relationship.sourceTable} → one ${relationship.targetTable}`;
    case 'one-to-many':
      return `One ${relationship.sourceTable} → many ${relationship.targetTable}`;
    case 'many-to-many':
      return `Many ${relationship.sourceTable} ↔ many ${relationship.targetTable}`;
    default:
      return `${relationship.sourceTable} → ${relationship.targetTable}`;
  }
}

export function cardinalityShort(relationship: Relationship): string {
  switch (relationship.type) {
    case 'one-to-one':
      return '1:1';
    case 'many-to-one':
      return 'N:1';
    case 'one-to-many':
      return '1:N';
    case 'many-to-many':
      return 'N:M';
    default:
      return '?';
  }
}

export function explainJunctionTable(schema: ParsedSchema, tableName: string): string | null {
  const j = schema.junctionTables.find((x) => x.table.toLowerCase() === tableName.toLowerCase());
  if (!j) return null;
  return `${j.table} looks like an associative (junction) entity resolving a many-to-many relationship between ${j.connects.join(
    ' and '
  )}. ${j.reason}`;
}

export function generateSchemaSummary(schema: ParsedSchema): string {
  if (schema.tables.length === 0) return 'No entities have been extracted yet.';
  const { stats } = schema;
  const parts = [
  `This schema declares ${stats.tables} entit${stats.tables === 1 ? 'y' : 'ies'} holding ${stats.columns} attribute(s) in total.`,
  stats.relationships > 0 ?
  `${stats.relationships} foreign key relationship(s) connect them.` :
  'No foreign keys were declared, so the entities are currently independent.',
  stats.junctionTables > 0 ?
  `${stats.junctionTables} table(s) look like associative entities resolving many-to-many relationships.` :
  ''];

  const largest = [...schema.tables].sort((a, b) => b.columns.length - a.columns.length)[0];
  if (largest) parts.push(`${largest.name} is the widest entity with ${largest.columns.length} attributes.`);
  return parts.filter(Boolean).join(' ');
}

export function generateSimulationSteps(schema: ParsedSchema): SimulationStep[] {
  const steps: SimulationStep[] = [];
  const push = (s: Omit<SimulationStep, 'index' | 'id'>) => {
    steps.push({ ...s, index: steps.length, id: `step_${steps.length}` });
  };

  const allTables = schema.tables.map((t) => t.name);
  const allRels = schema.relationships.map((r) => r.id);

  push({
    title: 'Parse SQL',
    subtitle: `${schema.tables.length} CREATE TABLE statement(s) detected`,
    body:
    'The raw text is stripped of comments, split into statements on top-level semicolons, and each statement is checked for the CREATE TABLE shape. Everything after this point is derived from what the parser actually read.',
    bullets: schema.tables.map((t) => `CREATE TABLE ${t.name} — line ${t.line}`),
    highlightTables: [],
    highlightColumns: [],
    highlightRelationships: [],
    revealTables: [],
    revealRelationships: []
  });

  push({
    title: 'Detect entities',
    subtitle: `${schema.tables.length} table(s) become entities`,
    body:
    'Each CREATE TABLE statement describes a distinct kind of thing being stored, so each one becomes an entity — a box in the ER diagram.',
    bullets: schema.tables.map(
      (t) => `${t.name} is identified as a database table and becomes an entity in the ER model.`
    ),
    highlightTables: allTables,
    highlightColumns: [],
    highlightRelationships: [],
    revealTables: allTables,
    revealRelationships: []
  });

  push({
    title: 'Extract attributes',
    subtitle: `${schema.stats.columns} column(s) become attributes`,
    body:
    'Every column inside a table becomes an attribute of that entity. The declared data type defines the domain of values the attribute may take.',
    bullets: schema.tables.map(
      (t) => `${t.name}: ${t.columns.map((c) => `${c.name} ${c.dataType}`).join(', ') || 'no columns'}`
    ),
    highlightTables: allTables,
    highlightColumns: schema.tables.flatMap((t) => t.columns.map((c) => `${t.name}.${c.name}`)),
    highlightRelationships: [],
    revealTables: allTables,
    revealRelationships: []
  });

  const pkTables = schema.tables.filter((t) => t.primaryKeys.length > 0);
  push({
    title: 'Identify primary keys',
    subtitle: `${pkTables.length} of ${schema.tables.length} entit${schema.tables.length === 1 ? 'y' : 'ies'} identified`,
    body:
    'A PRIMARY KEY constraint marks the attribute — or combination of attributes — that uniquely identifies each instance of the entity.',
    bullets: schema.tables.map((t) => explainPrimaryKey(t)),
    highlightTables: pkTables.map((t) => t.name),
    highlightColumns: schema.tables.flatMap((t) => t.primaryKeys.map((pk) => `${t.name}.${pk}`)),
    highlightRelationships: [],
    revealTables: allTables,
    revealRelationships: []
  });

  const fkTables = schema.tables.filter((t) => t.foreignKeys.length > 0);
  push({
    title: 'Detect foreign keys',
    subtitle: `${schema.stats.foreignKeys} foreign key constraint(s)`,
    body:
    'A foreign key is a column whose values must already exist in another table. Each one is the SQL trace of a relationship between two entities.',
    bullets:
    fkTables.length > 0 ?
    fkTables.flatMap((t) =>
    t.foreignKeys.map(
      (f) =>
      `${t.name}.${f.columns.join(', ')} → ${f.refTable}${
      f.refColumns.length ? `.${f.refColumns.join(', ')}` : ' (primary key)'}`

    )
    ) :
    ['No foreign keys were declared in this schema.'],
    highlightTables: fkTables.map((t) => t.name),
    highlightColumns: fkTables.flatMap((t) =>
    t.foreignKeys.flatMap((f) => f.columns.map((c) => `${t.name}.${c}`))
    ),
    highlightRelationships: [],
    revealTables: allTables,
    revealRelationships: []
  });

  push({
    title: 'Create relationships',
    subtitle: `${schema.relationships.length} relationship(s) drawn`,
    body:
    'Each resolved foreign key becomes an edge. Cardinality is inferred from uniqueness and nullability of the referencing columns.',
    bullets:
    schema.relationships.length > 0 ?
    schema.relationships.map(
      (r) => `${cardinalityLabel(r)} — via ${r.sourceTable}.${r.sourceColumn} → ${r.targetTable}.${r.targetColumn}`
    ) :
    ['No relationships could be drawn — there are no resolvable foreign keys.'],
    highlightTables: [],
    highlightColumns: [],
    highlightRelationships: allRels,
    revealTables: allTables,
    revealRelationships: allRels
  });

  push({
    title: 'Complete diagram',
    subtitle: generateSchemaSummary(schema),
    body:
    schema.junctionTables.length > 0 ?
    `The model is complete. ${schema.junctionTables.
    map((j) => `${j.table} resolves a many-to-many relationship between ${j.connects.join(' and ')}`).
    join('; ')}.` :
    'The model is complete. Select any entity or relationship in the canvas to inspect what the parser extracted for it.',
    bullets: schema.insights.slice(0, 4).map((i) => i.title),
    highlightTables: allTables,
    highlightColumns: [],
    highlightRelationships: allRels,
    revealTables: allTables,
    revealRelationships: allRels
  });

  return steps;
}

export const ExplanationEngine = {
  explainTable,
  explainColumn,
  explainPrimaryKey,
  explainForeignKey,
  explainRelationship,
  explainJunctionTable,
  generateSchemaSummary,
  generateSimulationSteps
};